    id integer generated by default as identity primary key,
    nombre varchar(100) not null unique
);
insert into app.materias (nombre)
select distinct trim(materia) from app.tutor_materias_legacy;
insert into app.materias (nombre) values ('Sin especificar') on conflict do nothing;
create table app.tutor_materias (
    tutor_id integer not null,
    materia_id integer not null,
    primary key (tutor_id, materia_id),
    constraint fk_tutor_materias_tutor foreign key (tutor_id) references app.tutores (id),
    constraint fk_tutor_materias_materia foreign key (materia_id) references app.materias (id)
);
insert into app.tutor_materias (tutor_id, materia_id)
select legacy.tutor_id, materia.id
from app.tutor_materias_legacy legacy
join app.materias materia on materia.nombre = trim(legacy.materia)
on conflict do nothing;
drop table app.tutor_materias_legacy;

