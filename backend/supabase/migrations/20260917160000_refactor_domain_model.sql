-- Unifica la identidad, completa las entidades del dominio y conserva los datos existentes.
alter table app.clientes rename to usuarios;
alter table app.usuarios add column fecha_creacion timestamp not null default current_timestamp;
alter table app.usuarios add column fecha_actualizacion timestamp not null default current_timestamp;
alter table app.usuarios add column version bigint not null default 0;

create table app.usuario_roles (
    usuario_id integer not null,
    rol varchar(30) not null check (rol in ('ESTUDIANTE', 'TUTOR', 'ADMINISTRADOR')),
    primary key (usuario_id, rol),
    constraint fk_usuario_roles_usuario foreign key (usuario_id) references app.usuarios (id)
);

alter table app.estudiantes rename column cliente_id to usuario_id;
alter table app.tutores rename column cliente_id to usuario_id;
alter table app.tutores drop column calificacion_promedio;

insert into app.usuario_roles (usuario_id, rol)
select usuario_id, 'ESTUDIANTE' from app.estudiantes;
insert into app.usuario_roles (usuario_id, rol)
select usuario_id, 'TUTOR' from app.tutores
on conflict do nothing;

insert into app.usuarios (nombre, apellido, correo, contrasena, telefono, activo)
select nombre, apellido, correo, contrasena, telefono, activo
from app.administradores administrador
where not exists (
    select 1 from app.usuarios usuario where lower(usuario.correo) = lower(administrador.correo)
);
insert into app.usuario_roles (usuario_id, rol)
select usuario.id, 'ADMINISTRADOR'
from app.usuarios usuario
join app.administradores administrador on lower(administrador.correo) = lower(usuario.correo)
on conflict do nothing;
insert into app.usuario_roles (usuario_id, rol)
select usuario.id, 'ESTUDIANTE'
from app.usuarios usuario
where not exists (select 1 from app.usuario_roles rol where rol.usuario_id = usuario.id);
drop table app.administradores;

drop index if exists app.ux_clientes_correo_lower;
create unique index ux_usuarios_correo_lower on app.usuarios (lower(correo));
drop index if exists app.ix_estudiantes_cliente_id;
drop index if exists app.ix_tutores_cliente_id;
create index ix_estudiantes_usuario_id on app.estudiantes (usuario_id);
create index ix_tutores_usuario_id on app.tutores (usuario_id);

