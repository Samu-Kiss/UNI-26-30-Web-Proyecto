create table if not exists app.disponibilidades_tutor (
    id integer generated by default as identity primary key,
    tutor_id integer not null,
    dia_semana varchar(15) not null check (dia_semana in (
        'LUNES', 'MARTES', 'MIERCOLES', 'JUEVES', 'VIERNES', 'SABADO', 'DOMINGO')),
    hora_inicio time(0) without time zone not null,
    hora_fin time(0) without time zone not null,
    constraint ck_disponibilidad_horas check (hora_fin > hora_inicio),
    constraint fk_disponibilidad_tutor foreign key (tutor_id) references app.tutores (id),
    constraint ux_disponibilidad_tutor_horario unique (tutor_id, dia_semana, hora_inicio, hora_fin)
);

create table if not exists app.resenas (
    id integer generated by default as identity primary key,
    reserva_id integer not null unique,
    calificacion integer not null check (calificacion between 1 and 5),
    comentario varchar(1000),
    fecha_creacion timestamp not null,
    constraint fk_resena_reserva foreign key (reserva_id) references app.reservas (id)
);

-- Older development databases created these tables through Hibernate before this migration.
-- Keep their rows, but remove duplicated participants: the reservation is authoritative.
do $$
begin
    if exists (select 1 from information_schema.columns
            where table_schema = 'app' and table_name = 'resenas' and column_name = 'estudiante_id') then
        if exists (select 1 from app.resenas review join app.reservas booking on booking.id = review.reserva_id
                where review.estudiante_id <> booking.estudiante_id or review.tutor_id <> booking.tutor_id) then
            raise exception 'Review participants disagree with their reservation; reconcile before migrating';
        end if;
        alter table app.resenas drop column estudiante_id;
        alter table app.resenas drop column tutor_id;
    end if;
    if not exists (select 1 from pg_constraint
            where conrelid = 'app.disponibilidades_tutor'::regclass and conname = 'ck_disponibilidad_horas') then
        alter table app.disponibilidades_tutor add constraint ck_disponibilidad_horas
            check (hora_fin > hora_inicio);
    end if;
    if not exists (select 1 from pg_constraint
            where conrelid = 'app.disponibilidades_tutor'::regclass
                and conname = 'ux_disponibilidad_tutor_horario') then
        alter table app.disponibilidades_tutor add constraint ux_disponibilidad_tutor_horario
            unique (tutor_id, dia_semana, hora_inicio, hora_fin);
    end if;
end;
$$;
alter table app.resenas alter column comentario drop not null;
alter table app.resenas alter column comentario type varchar(1000);
alter table app.disponibilidades_tutor alter column dia_semana type varchar(15);

