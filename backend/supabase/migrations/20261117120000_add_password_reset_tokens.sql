create table if not exists app.tokens_recuperacion (
    id integer generated by default as identity primary key,
    usuario_id integer not null,
    token varchar(64) not null unique,
    fecha_expiracion timestamp not null,
    usado boolean not null default false,
    fecha_creacion timestamp not null default current_timestamp,
    constraint fk_token_recuperacion_usuario foreign key (usuario_id)
        references app.usuarios (id) on delete cascade
);

create index if not exists ix_tokens_recuperacion_token on app.tokens_recuperacion (token);
create index if not exists ix_tokens_recuperacion_usuario on app.tokens_recuperacion (usuario_id);

alter table app.tokens_recuperacion enable row level security;
